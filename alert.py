#!/usr/bin/env python3
"""Shopify competitor alerts: price drops, restocks, new and sold-out products since the last run, sent to Slack or e-mail.

Configuration: config.yml (the only file you need to edit).
Secrets / environment variables:
  APIFY_TOKEN        required, your Apify API token (the Actor run is billed to your Apify account)
  SLACK_WEBHOOK_URL  optional, Slack incoming-webhook URL
  SMTP_HOST, SMTP_PORT, SMTP_USERNAME, SMTP_PASSWORD, EMAIL_TO, EMAIL_FROM
                     optional, e-mail delivery (EMAIL_TO may be a comma-separated list)
Without Slack/SMTP the digest is printed to the log and the GitHub job summary, and saved to out/.

Usage: python alert.py [--config config.yml] [--out out] [--dry-run] [--items-file items.json]
"""
from __future__ import annotations

import argparse
import csv
import html
import json
import os
import smtplib
import ssl
import sys
import urllib.request
from dataclasses import dataclass, field
from datetime import datetime, timedelta, timezone
from decimal import Decimal
from email.message import EmailMessage
from pathlib import Path

import yaml

ACTOR_ID = "lindenbyte/shopify-catalog-change-monitor"
STORE_URL = "https://apify.com/lindenbyte/shopify-catalog-change-monitor"
REPO_URL = "https://github.com/lindenbyte-studio/shopify-competitor-price-alerts"
MAX_SLACK_BLOCKS = 50


# ---------------------------------------------------------------- digest model
@dataclass
class Entry:
    title: str
    url: str | None = None
    meta: list[str] = field(default_factory=list)
    detail: str | None = None


@dataclass
class Digest:
    title: str
    summary: str
    entries: list[Entry] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)
    total: int = 0  # number of results before truncation to max_items_in_message


def _trim(text: str | None, n: int) -> str:
    text = " ".join(str(text or "").split())
    return text if len(text) <= n else text[: n - 1].rstrip() + "…"


# ---------------------------------------------------------------- renderers
def _slack_escape(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def build_slack_payload(d: Digest) -> dict:
    """Slack incoming-webhook payload (Block Kit) for a digest. Pure function, unit-tested."""
    blocks: list[dict] = [
        {"type": "header", "text": {"type": "plain_text", "text": _trim(d.title, 150), "emoji": True}},
        {"type": "context", "elements": [{"type": "mrkdwn", "text": _slack_escape(_trim(d.summary, 300))}]},
    ]
    room = MAX_SLACK_BLOCKS - len(blocks) - 2  # keep space for "more" + notes
    shown = d.entries[:room]
    for e in shown:
        title = _slack_escape(_trim(e.title, 200))
        line = f"*<{e.url}|{title}>*" if e.url else f"*{title}*"
        if e.meta:
            line += "\n" + _slack_escape(" · ".join(m for m in e.meta if m))
        if e.detail:
            line += "\n>" + _slack_escape(_trim(e.detail, 300))
        blocks.append({"type": "section", "text": {"type": "mrkdwn", "text": _trim(line, 2900)}})
    hidden = d.total - len(shown)
    if hidden > 0:
        blocks.append({"type": "context", "elements": [{"type": "mrkdwn",
                       "text": f"…and {hidden} more (full list in the workflow run's artifact)."}]})
    if d.notes:
        blocks.append({"type": "context", "elements": [{"type": "mrkdwn",
                       "text": _trim(_slack_escape("Notes: " + " | ".join(d.notes)), 2900)}]})
    return {"text": _trim(f"{d.title}: {d.summary}", 300), "blocks": blocks, "unfurl_links": False}


def render_markdown(d: Digest) -> str:
    out = [f"## {d.title}", "", d.summary, ""]
    for e in d.entries:
        title = e.title.replace("[", "(").replace("]", ")")
        out.append(f"- **[{title}]({e.url})**" if e.url else f"- **{title}**")
        if e.meta:
            out.append(f"  {' · '.join(m for m in e.meta if m)}")
        if e.detail:
            out.append(f"  > {_trim(e.detail, 300)}")
    if d.total > len(d.entries):
        out.append(f"\n…and {d.total - len(d.entries)} more (see items.csv in the run artifact).")
    if d.notes:
        out += ["", "**Notes**", *[f"- {n}" for n in d.notes]]
    out += ["", f"<sub>Generated by [{REPO_URL.rsplit('/', 1)[-1]}]({REPO_URL}) using the Apify Actor [{ACTOR_ID}]({STORE_URL}).</sub>", ""]
    return "\n".join(out)


def render_email(d: Digest) -> tuple[str, str, str]:
    """Returns (subject, plain text, html)."""
    subject = _trim(f"{d.title}: {d.summary}", 150)
    text = [d.title, d.summary, ""]
    rows = []
    for e in d.entries:
        text.append(f"* {e.title}")
        if e.url:
            text.append(f"  {e.url}")
        if e.meta:
            text.append("  " + " · ".join(m for m in e.meta if m))
        if e.detail:
            text.append("  " + _trim(e.detail, 300))
        text.append("")
        link = (f'<a href="{html.escape(e.url)}" style="font-weight:600">{html.escape(e.title)}</a>' if e.url
                else f"<b>{html.escape(e.title)}</b>")
        meta = f'<div style="color:#555;font-size:13px">{html.escape(" · ".join(m for m in e.meta if m))}</div>' if e.meta else ""
        det = f'<div style="color:#333;font-size:13px">{html.escape(_trim(e.detail, 300))}</div>' if e.detail else ""
        rows.append(f'<li style="margin-bottom:10px">{link}{meta}{det}</li>')
    more = d.total - len(d.entries)
    if more > 0:
        text.append(f"...and {more} more (full list in the workflow run's artifact).")
    if d.notes:
        text += ["", "Notes:", *[f"- {n}" for n in d.notes]]
    text += ["", f"Sent by {REPO_URL} (Apify Actor: {STORE_URL})"]
    notes_html = ("<p><b>Notes</b></p><ul>" + "".join(f"<li>{html.escape(n)}</li>" for n in d.notes) + "</ul>") if d.notes else ""
    more_html = f"<p>…and {more} more (full list in the workflow run's artifact).</p>" if more > 0 else ""
    body = (f'<div style="font-family:Arial,sans-serif;max-width:720px"><h2 style="margin-bottom:4px">{html.escape(d.title)}</h2>'
            f'<p style="color:#555;margin-top:0">{html.escape(d.summary)}</p><ul style="padding-left:18px">{"".join(rows)}</ul>'
            f'{more_html}{notes_html}<p style="color:#888;font-size:12px">Sent by <a href="{REPO_URL}">{REPO_URL.rsplit("/", 1)[-1]}</a> '
            f'using the Apify Actor <a href="{STORE_URL}">{html.escape(ACTOR_ID)}</a>.</p></div>')
    return subject, "\n".join(text), body


# ---------------------------------------------------------------- outputs and notifiers
def _flat(v):
    if isinstance(v, (list, tuple)):
        return "; ".join(_flat(x) for x in v)
    if isinstance(v, dict):
        return json.dumps(v, ensure_ascii=False)
    return "" if v is None else str(v)


def write_outputs(items: list[dict], d: Digest, outdir: Path) -> None:
    outdir.mkdir(parents=True, exist_ok=True)
    (outdir / "items.json").write_text(json.dumps(items, indent=2, ensure_ascii=False), encoding="utf-8")
    cols: list[str] = []
    for it in items:
        cols += [k for k in it if k not in cols]
    with open(outdir / "items.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(cols)
        for it in items:
            w.writerow([_flat(it.get(c)) for c in cols])
    (outdir / "digest.md").write_text(render_markdown(d), encoding="utf-8")


def post_slack(webhook: str, payload: dict) -> None:
    req = urllib.request.Request(webhook, data=json.dumps(payload).encode(), method="POST",
                                 headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=30) as resp:
        if resp.status >= 300:
            raise RuntimeError(f"Slack webhook answered HTTP {resp.status}")


def send_email(d: Digest) -> None:
    host, user, pw = os.environ["SMTP_HOST"], os.environ.get("SMTP_USERNAME", ""), os.environ.get("SMTP_PASSWORD", "")
    port = int(os.environ.get("SMTP_PORT") or 587)
    to = [a.strip() for a in os.environ["EMAIL_TO"].split(",") if a.strip()]
    subject, text, body = render_email(d)
    msg = EmailMessage()
    msg["Subject"], msg["From"], msg["To"] = subject, os.environ.get("EMAIL_FROM") or user, ", ".join(to)
    msg.set_content(text)
    msg.add_alternative(body, subtype="html")
    ctx = ssl.create_default_context()
    if port == 465:
        with smtplib.SMTP_SSL(host, port, context=ctx, timeout=60) as s:
            if user:
                s.login(user, pw)
            s.send_message(msg)
    else:
        with smtplib.SMTP(host, port, timeout=60) as s:
            s.starttls(context=ctx)
            if user:
                s.login(user, pw)
            s.send_message(msg)


# ---------------------------------------------------------------- Apify
def run_actor(token: str, run_input: dict, alert_cfg: dict):
    """Runs the Actor and waits for it. Returns (items, run, kv_store_client)."""
    from apify_client import ApifyClient  # imported here so tests don't need the package

    client = ApifyClient(token)
    max_charge = alert_cfg.get("max_charge_usd")
    run = client.actor(ACTOR_ID).call(
        run_input=run_input,
        max_total_charge_usd=Decimal(str(max_charge)) if max_charge else None,
        run_timeout=timedelta(minutes=int(alert_cfg.get("timeout_minutes") or 30)),
    )
    if run is None:
        raise RuntimeError("The Actor run did not finish in time.")
    print(f"Actor run {run.id}: {run.status}. {run.status_message or ''}")
    # charged_event_counts on the just-finished run object can lag behind; the console page is authoritative.
    print(f"Run details, cost and log: https://console.apify.com/actors/{run.act_id}/runs/{run.id}")
    if run.status != "SUCCEEDED":
        raise RuntimeError(f"Actor run {run.id} ended with status {run.status}: {run.status_message}")
    items = list(client.dataset(run.default_dataset_id).iterate_items(clean=True))
    return items, run, client.key_value_store(run.default_key_value_store_id)


def load_config(path: Path) -> dict:
    cfg = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    cfg.setdefault("input", {})
    cfg.setdefault("alert", {})
    return cfg


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--config", default="config.yml")
    ap.add_argument("--out", default="out")
    ap.add_argument("--dry-run", action="store_true", help="build the digest but don't send Slack/e-mail")
    ap.add_argument("--items-file", help="use items from a JSON file instead of running the Actor (preview/testing)")
    args = ap.parse_args(argv)

    cfg = load_config(Path(args.config))
    alert_cfg = cfg["alert"]
    run_input = build_input(cfg)
    kv = None
    if args.items_file:
        items = json.loads(Path(args.items_file).read_text(encoding="utf-8"))
    else:
        token = os.environ.get("APIFY_TOKEN")
        if not token:
            msg = "APIFY_TOKEN is not set. Add it as a repository secret (Settings > Secrets and variables > Actions)."
            if os.environ.get("GITHUB_EVENT_NAME") == "schedule":
                print(f"::warning::{msg} Skipping this scheduled run.")
                return 0
            print(msg, file=sys.stderr)
            return 2
        items, _run, kv = run_actor(token, run_input, alert_cfg)

    digest, kept = make_digest(items, cfg, kv)
    write_outputs(kept, digest, Path(args.out))
    md = render_markdown(digest)
    if os.environ.get("GITHUB_STEP_SUMMARY"):
        with open(os.environ["GITHUB_STEP_SUMMARY"], "a", encoding="utf-8") as f:
            f.write(md + "\n")

    if digest.total == 0 and not alert_cfg.get("send_when_empty", False):
        print(f"Nothing new: {digest.summary} No message sent.")
        for n in digest.notes:
            print(f"  note: {n}")
        return 0

    sent = []
    if args.dry_run:
        print("--dry-run: not sending.")
    else:
        if os.environ.get("SLACK_WEBHOOK_URL"):
            post_slack(os.environ["SLACK_WEBHOOK_URL"], build_slack_payload(digest))
            sent.append("Slack")
        if os.environ.get("SMTP_HOST") and os.environ.get("EMAIL_TO"):
            send_email(digest)
            sent.append("e-mail")
    print(md)
    print(f"Delivered via: {', '.join(sent) or 'job summary / log only (no Slack or SMTP secrets set)'}")
    return 0


# ---------------------------------------------------------------- Shopify Catalog & Change Monitor specifics
LABELS = {
    "price_drop": "Price drop", "price_increase": "Price increase", "restocked": "Back in stock",
    "sold_out": "Sold out", "new": "New product", "removed": "Removed",
}
ORDER = ["price_drop", "restocked", "new", "price_increase", "sold_out", "removed"]


def build_input(cfg: dict) -> dict:
    run_input = dict(cfg["input"])
    if not run_input.get("stores"):
        raise SystemExit("config.yml: input.stores is empty. Add at least one Shopify store domain.")
    run_input["mode"] = "changes"  # alerts = only what changed since the previous run
    run_input.setdefault("stateKey", "github-alerts")
    return run_input


def _money(v, cur) -> str:
    if v is None:
        return "?"
    s = f"{v:,.2f}" if isinstance(v, (int, float)) else str(v)
    return f"{s} {cur}" if cur else s


def change_entry(it: dict) -> Entry:
    t = it.get("changeType")
    cur = it.get("currency") or ""
    label = LABELS.get(t, t or "Change")
    if t in ("price_drop", "price_increase"):
        pct = it.get("priceChangePct")
        what = f"{label} {pct:+.0f}%" if isinstance(pct, (int, float)) else label
        price = f"{_money(it.get('oldPrice'), cur)} → {_money(it.get('newPrice'), cur)}"
    elif t == "removed":
        what, price = label, f"was {_money(it.get('oldPrice'), cur)}"
    else:
        what, price = label, _money(it.get("newPrice"), cur)
    vendor, store = (it.get("vendor") or "").strip(), it.get("store") or ""
    brand = vendor.split()[0].strip(",|-").lower() if vendor else ""
    show_vendor = vendor and brand not in store.lower().replace("-", "")  # skip "Gymshark" on gymshark.com
    meta = [what, price, store, vendor if show_vendor else None]
    return Entry(title=it.get("title") or it.get("handle") or "Product", url=it.get("url"), meta=[m for m in meta if m])


def make_digest(items: list[dict], cfg: dict, kv) -> tuple[Digest, list[dict]]:
    alert_cfg = cfg["alert"]
    limit = int(alert_cfg.get("max_items_in_message") or 30)
    title = alert_cfg.get("title") or "Shopify competitor changes"
    changes = [it for it in items if it.get("rowType") == "change"]
    status = [it for it in items if it.get("rowType") == "status"]
    changes.sort(key=lambda it: (ORDER.index(it["changeType"]) if it.get("changeType") in ORDER else 99,
                                 -abs(it.get("priceChangePct") or 0), it.get("store") or "", it.get("title") or ""))
    counts: dict[str, int] = {}
    for it in changes:
        counts[it.get("changeType")] = counts.get(it.get("changeType"), 0) + 1

    notes = []
    run_summary = None
    if kv is not None:
        rec = kv.get_record("RUN-SUMMARY")
        run_summary = rec["value"] if rec else None
    if (run_summary or {}).get("stoppedReason"):
        notes.append(f"Run stopped early: {run_summary['stoppedReason']} (alert.max_charge_usd). "
                     "Changes not reported yet are kept and arrive next run.")
    baseline = [s for s in status if s.get("status") == "baseline-recorded"]
    if baseline:
        notes.append("Baseline recorded for " + ", ".join(f"{s.get('store')} ({s.get('productsRecorded', '?')} products)" for s in baseline)
                     + ". The next run reports changes.")
    for s in status:
        if s.get("status") != "baseline-recorded":
            notes.append(f"{s.get('input') or s.get('store')}: {s.get('status')}. {s.get('detail') or ''}".strip())

    if changes:
        summary = f"{len(changes)} change(s): " + ", ".join(f"{counts[k]} {LABELS.get(k, k).lower()}" for k in ORDER if k in counts) + "."
    elif baseline and len(baseline) == len(status):
        summary = f"Baseline recorded for {len(baseline)} store(s). From the next run you get only changes."
    else:
        summary = "No changes since the last run."
    entries = [change_entry(it) for it in changes[:limit]]
    return Digest(title=title, summary=summary, entries=entries, notes=notes, total=len(changes)), changes


if __name__ == "__main__":
    sys.exit(main())
